#!/usr/bin/env node
// Generates assets/js/firebase-config.js from .env.production + .env.development.
// Reads ONLY NEXT_PUBLIC_* keys (public web SDK config). Server/Admin keys in the
// same files are never read, never written, never shipped to the browser.
//
//   node scripts/generate-firebase-config.mjs                     -> both envs, routed by hostname (committed file)
//   node scripts/generate-firebase-config.mjs --only=development  -> dev config only (CI build for dev.connectusonline.org)
//   node scripts/generate-firebase-config.mjs --only=production   -> prod config only
//   node scripts/generate-firebase-config.mjs --check             -> exit 1 if the committed file is stale
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(ROOT, 'assets/js/firebase-config.js');
const CHECK = process.argv.includes('--check');
const ONLY = (process.argv.find(a => a.startsWith('--only=')) || '').split('=')[1] || null;

const ENVS = {
    production: {
        file: '.env.production',
        projectId: 'school-grade-tracker',
        hosts: ['connectusonline.org', 'www.connectusonline.org', 'school-grade-tracker.web.app', 'school-grade-tracker.firebaseapp.com'],
    },
    development: {
        file: '.env.development',
        projectId: 'dev-school-grade-tracker',
        hosts: ['dev.connectusonline.org', 'localhost', '127.0.0.1', 'dev-school-grade-tracker.web.app', 'dev-school-grade-tracker.firebaseapp.com'],
    },
};

const KEY_MAP = {
    NEXT_PUBLIC_FIREBASE_API_KEY:             'apiKey',
    NEXT_PUBLIC_FIREBASE_AUTH_DOMAIN:         'authDomain',
    NEXT_PUBLIC_FIREBASE_DATABASE_URL:        'databaseURL',
    NEXT_PUBLIC_FIREBASE_PROJECT_ID:          'projectId',
    NEXT_PUBLIC_FIREBASE_STORAGE_BUCKET:      'storageBucket',
    NEXT_PUBLIC_FIREBASE_MESSAGING_SENDER_ID: 'messagingSenderId',
    NEXT_PUBLIC_FIREBASE_APP_ID:              'appId',
    NEXT_PUBLIC_FIREBASE_MEASUREMENT_ID:      'measurementId',
};
const REQUIRED = ['apiKey', 'authDomain', 'projectId', 'storageBucket', 'messagingSenderId', 'appId'];

function fail(msg) { console.error(`✖ ${msg}`); process.exit(1); }

if (ONLY && !ENVS[ONLY]) fail(`--only must be one of: ${Object.keys(ENVS).join(', ')}`);
if (ONLY && CHECK) fail('--check validates the committed two-environment file; do not combine with --only.');

function parseEnv(path) {
    if (!existsSync(path)) fail(`${path} not found.`);
    const out = {};
    for (const raw of readFileSync(path, 'utf8').split(/\r?\n/)) {
        const m = raw.match(/^\s*(NEXT_PUBLIC_[A-Z0-9_]+)\s*=\s*(.*)\s*$/);
        if (!m) continue;
        out[m[1]] = m[2].replace(/^(['"])(.*)\1$/, '$2');
    }
    return out;
}

const targets = ONLY ? [ONLY] : Object.keys(ENVS);
const configs = {};
const hostEnv = {};

for (const env of targets) {
    const { file, projectId, hosts } = ENVS[env];
    const vars = parseEnv(resolve(ROOT, file));
    const cfg = {};
    for (const [k, field] of Object.entries(KEY_MAP)) if (vars[k]) cfg[field] = vars[k];
    const missing = REQUIRED.filter(f => !cfg[f]);
    if (missing.length) fail(`${file}: missing ${missing.join(', ')}.`);
    if (cfg.projectId !== projectId) fail(`${file}: projectId is "${cfg.projectId}", expected "${projectId}".`);
    configs[env] = cfg;

    const extra = (vars.NEXT_PUBLIC_APP_HOSTNAMES || '').split(',').map(s => s.trim()).filter(Boolean);
    for (const h of [...hosts, ...extra]) {
        if (hostEnv[h] && hostEnv[h] !== env) fail(`Hostname "${h}" mapped to both ${hostEnv[h]} and ${env}.`);
        hostEnv[h] = env;
    }
}

const fallback = ONLY || 'production';

const body = `// AUTO-GENERATED by scripts/generate-firebase-config.mjs — do not edit by hand.
// Source: ${targets.map(t => ENVS[t].file).join(' / ')} (NEXT_PUBLIC_* keys only).
// Firebase web config is a public client identifier, not a secret; access is
// enforced by firestore.rules / storage.rules / database.rules.json.
//
// Environment is chosen by window.location.hostname:
//   development: dev.connectusonline.org, localhost, 127.0.0.1, *.web.app/*.firebaseapp.com of dev-school-grade-tracker
//   production : connectusonline.org, www.connectusonline.org, *.web.app/*.firebaseapp.com of school-grade-tracker
// Unlisted hosts fall back to "${fallback}". On localhost, firebase-init.js still
// routes every SDK to the local emulators — never to live dev or prod data.

export const FIREBASE_CONFIGS = ${JSON.stringify(configs, null, 4)};

const HOST_ENV = ${JSON.stringify(hostEnv, null, 4)};

const host = typeof window !== 'undefined' && window.location ? window.location.hostname : '';

export const FIREBASE_ENV = HOST_ENV[host] || '${fallback}';
export const firebaseConfig = FIREBASE_CONFIGS[FIREBASE_ENV];
`;

if (CHECK) {
    const current = existsSync(OUT) ? readFileSync(OUT, 'utf8').replace(/\r\n/g, '\n') : '';
    if (current !== body) fail('assets/js/firebase-config.js is stale. Run: npm run config:generate, then commit.');
    console.log('✔ firebase-config.js up to date');
} else {
    writeFileSync(OUT, body);
    console.log(`✔ wrote ${OUT}${ONLY ? ` (${ONLY} only)` : ''}`);
}
